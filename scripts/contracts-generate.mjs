// Generates TypeScript types from the contract snapshot in contracts/ (ADR 0004).
// `--check` writes nothing, and fails if the committed types are out of date.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const contractsDir = "contracts";
const outputDir = join("src", "lib", "api", "generated");
const suffix = ".openapi.yaml";

const header = `// Generated by scripts/contracts-generate.mjs from contracts/. Do not edit.\n\n`;

export async function generateAll() {
  const files = new Map();
  const contracts = readdirSync(contractsDir).filter((file) =>
    file.endsWith(suffix),
  );

  for (const contract of contracts) {
    const name = contract.slice(0, -suffix.length);
    const ast = await openapiTS(pathToFileURL(join(contractsDir, contract)));
    files.set(`${name}.ts`, header + astToString(ast).replaceAll("\r\n", "\n"));
  }

  return files;
}

function existingFiles() {
  if (!existsSync(outputDir)) return [];
  return readdirSync(outputDir).filter((file) => file.endsWith(".ts"));
}

function check(generated) {
  const stale = [];

  for (const [file, content] of generated) {
    const path = join(outputDir, file);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current !== content) stale.push(file);
  }
  for (const file of existingFiles()) {
    if (!generated.has(file)) stale.push(`${file} (no matching contract)`);
  }

  if (stale.length > 0) {
    console.error(
      "Generated API types are out of date. Run `pnpm contracts:generate`.",
    );
    for (const file of stale) console.error(`  ${file}`);
    process.exitCode = 1;
    return;
  }
  console.log(
    `Generated API types are up to date (${generated.size} contracts).`,
  );
}

function write(generated) {
  mkdirSync(outputDir, { recursive: true });
  for (const file of existingFiles()) {
    if (!generated.has(file)) rmSync(join(outputDir, file));
  }
  for (const [file, content] of generated) {
    writeFileSync(join(outputDir, file), content);
  }
  console.log(
    `Generated types for ${generated.size} contracts in ${outputDir}.`,
  );
}

const generated = await generateAll();
if (process.argv.includes("--check")) check(generated);
else write(generated);
